const parse = (sector: string, asOf: string, rows: string): Company[] =>
  rows.trim().split('\n').map(line => {
    const [code, name, batch, rating, price, scen, ratio, thesis, risk, next] = line.split('|')
    const metrics: [string, string][] = []
    if (price) metrics.push(['价格锚点', price])
    if (scen) metrics.push(['Bear / Base / Bull', scen])
    if (ratio) metrics.push(['Base / Bear 赔率', ratio])
    return {
      code, name, market: 'us' as Market, sector, batch, rating,
      headline: thesis ? split(thesis)[0] : rating,
      metrics, thesis: split(thesis || ''), risk: split(risk || ''), next: split(next || ''),
      asOf, url: notionUrl(notionIds[code]),
    }
  })

