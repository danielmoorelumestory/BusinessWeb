import { readFile, access, mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

export async function generateBlogCatalog({ root, output = path.join(root, 'src/features/blog/generated-catalog.ts') }) {
  const manifest = JSON.parse(await readFile(path.join(root, 'src/content/blog/manifest.json'), 'utf8'))
  if (!Array.isArray(manifest)) throw new Error('Blog manifest must be an array')
  const published = manifest.filter(entry => entry.status === 'published')
  const seen = new Set()
  const loaders = []
  for (const entry of published) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(entry.slug || '') || seen.has(entry.slug)) throw new Error(`Invalid or duplicate blog slug: ${entry.slug}`)
    if (entry.file !== `src/content/blog/posts/${entry.slug}.md`) throw new Error(`Invalid blog file: ${entry.slug}`)
    if (!entry.title || !entry.summary || !entry.publishedAt) throw new Error(`Missing publication metadata: ${entry.slug}`)
    await access(path.join(root, entry.file))
    seen.add(entry.slug)
    loaders.push(`  ${JSON.stringify(entry.file)}: () => import('../../content/blog/posts/${entry.slug}.md?raw').then(module => module.default),`)
  }
  const code = `// Generated by scripts/generate-blog-catalog.mjs. Do not edit by hand.\nexport const blogMarkdownLoaders: Record<string, () => Promise<string>> = {\n${loaders.join('\n')}\n}\n`
  const metadata = `// Generated by scripts/generate-blog-catalog.mjs. Do not edit by hand.\nimport type { BlogEntry } from './catalog'\n\nexport const publishedManifest: BlogEntry[] = ${JSON.stringify(published, null, 2)}\n`
  await mkdir(path.dirname(output), { recursive: true })
  await writeFile(output, code)
  await writeFile(path.join(path.dirname(output), 'generated-manifest.ts'), metadata)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateBlogCatalog({ root: process.cwd() }).catch(error => { console.error(error); process.exitCode = 1 })
}
